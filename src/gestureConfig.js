/**
 * 手势总开关 —— 调试期「暂时关掉某个手势」用，改一个 false 就行，不用删代码。
 *
 * fist：握拳 → 树体向下收拢（InteractionRouter.collapse）。
 *   真人比心时手指常是半握状态，MediaPipe 很容易判成 fist，树被压塌、画面里看不清心形，
 *   所以先关掉，等比心调稳了再改回 true。
 *
 * burst：张手炸裂。触发条件已经和握拳解绑：**单手抓一把（五指收向掌心）后 1.2 秒内张开手掌**
 *   才炸一次。这样不用先握拳，也不会被半握比心误触。
 *
 * call：打电话 / 比 6 —— 拇指和小指伸出、中间三指收拢 → 弹幕「666 / 想我就给我打电话」。
 *
 * like：点赞 —— 拇指竖起朝上、其余四指全部收回 → 粒子大拇指 + 666，成形后被风吹散。
 *
 * ok：单手 OK —— 拇指食指捏成圈、中指无名指小指伸开 → 满屏爱心 + 银色流星雨 +
 *   底部升空的烟花，散掉之后浮出「miss you」，最后字也随风散尽。整段约 8.5 秒。
 *
 * tray：掌心向上接礼物。掌心朝上在日常动作里太常见（抬手、比心都会经过），误触率高，先关掉。
 *
 * 关掉某项后，对应的 HUD 提示条也会自动隐藏，页面上看到的就是真实可用的手势。
 * 提示条的 data-k 与这里的键名不一定同名（张开那条是 data-k="open"，归 burst 管），
 * 映射表在 main.js 的 HINT_SWITCH。
 */
export const GESTURE_SWITCH = {
  fist: false,   // 握拳收拢
  burst: true,   // 张手炸裂：抓取 → 张开手掌
  clap: true,    // 拍手爆雪
  call: true,    // 打电话（拇指+小指）× 弹幕
  like: true,    // 点赞（拇指竖起）× 粒子大拇指 + 666
  ok: true,      // 单手 OK（拇指食指成圈）× 爱心 + 流星雨 + 烟花 + miss you
  tray: false,   // 掌心向上接礼物
  heart: true,   // 双手比心
};
